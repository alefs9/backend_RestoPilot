-- No elimina tablas ni inserta cuentas/datos de muestra.
CREATE TABLE public.categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurante_id BIGINT NOT NULL,
 nombre VARCHAR(100) NOT NULL,
 descripcion TEXT,
 creado_en TIMESTAMP(6),
 actualizado_en TIMESTAMP(6)
);
CREATE TABLE public.platos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurante_id BIGINT NOT NULL,
 categoria_id BIGINT NOT NULL REFERENCES public.categorias(id),
 nombre VARCHAR(150) NOT NULL,
 descripcion TEXT,
 precio NUMERIC(10,2) NOT NULL,
 ingredientes TEXT,
 alergenos TEXT,
 complejidad VARCHAR(50),
 tiempo_preparacion_minutos INTEGER,
 disponible BOOLEAN NOT NULL,
 imagen_url VARCHAR(255),
 creado_en TIMESTAMP(6),
 actualizado_en TIMESTAMP(6)
);
CREATE TABLE public.mesas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurante_id BIGINT NOT NULL REFERENCES public.restaurantes(id),
 numero INTEGER NOT NULL,
 capacidad INTEGER NOT NULL,
 coordenada_x DOUBLE PRECISION NOT NULL,
 coordenada_y DOUBLE PRECISION NOT NULL,
 activo BOOLEAN NOT NULL,
 creado_en TIMESTAMP(6) NOT NULL,
 actualizado_en TIMESTAMP(6)
);
CREATE TABLE public.pedidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 restaurante_id BIGINT NOT NULL REFERENCES public.restaurantes(id),
 cliente_id BIGINT NOT NULL REFERENCES public.usuarios(id),
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','EN_PREPARACION','LISTO','ENTREGADO','CANCELADO')),
 tipo_entrega VARCHAR(20) NOT NULL CHECK (tipo_entrega IN ('SALON','LLEVAR','RECOGER','DELIVERY')),
 total NUMERIC(10,2) NOT NULL,
 fecha_creacion TIMESTAMP(6) NOT NULL,
 limite_cancelacion TIMESTAMP(6),
 mesa_id BIGINT REFERENCES public.mesas(id),
 direccion_entrega VARCHAR(255)
);
CREATE TABLE public.detalles_pedido (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id BIGINT NOT NULL REFERENCES public.pedidos(id),
 plato_id BIGINT NOT NULL REFERENCES public.platos(id),
 cantidad INTEGER NOT NULL,
 subtotal NUMERIC(10,2) NOT NULL,
 precio_unitario NUMERIC(10,2),
 nombre_plato_snapshot VARCHAR(255) NOT NULL,
 notas TEXT
);
CREATE TABLE public.reservas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 motivo_rechazo VARCHAR(300),
 mesa_id BIGINT NOT NULL REFERENCES public.mesas(id),
 usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id),
 restaurante_id BIGINT NOT NULL REFERENCES public.restaurantes(id),
 fecha DATE NOT NULL,
 hora_inicio TIME(6) NOT NULL,
 hora_fin TIME(6) NOT NULL,
 numero_comensales INTEGER NOT NULL,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','CONFIRMADA','RECHAZADA','CANCELADA','EXPIRADA','COMPLETADA')),
 llegada_registrada_en TIMESTAMP(6),
 completada_en TIMESTAMP(6),
 expirada_en TIMESTAMP(6),
 notas VARCHAR(500),
 creado_en TIMESTAMP(6) NOT NULL,
 actualizado_en TIMESTAMP(6)
);
CREATE TABLE public.notificaciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL,
 mensaje VARCHAR(500) NOT NULL,
 fecha_creacion TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_notificaciones_usuario_fecha ON public.notificaciones(usuario_id, fecha_creacion DESC);
